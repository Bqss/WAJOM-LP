export function t(key: string): string {
	return messages[locale.current][key] ?? messages.ms[key] ?? key;
}

export function isLocale(value: string | null): value is Locale {
	return value === 'ms' || value === 'en';
}

export function setLocale(next: Locale) {
	locale.current = next;

	if (typeof window !== 'undefined') {
		try {
			localStorage.setItem(LOCALE_STORAGE_KEY, next);
		} catch {
			// Storage can be unavailable in private browsing; the in-memory locale still works.
		}
		document.documentElement.lang = next;
		document.documentElement.dataset.locale = next;
	}
}

export function initializeLocale() {
	if (typeof window === 'undefined') return;

	let saved: string | null = null;
	try {
		saved = localStorage.getItem(LOCALE_STORAGE_KEY);
	} catch {
		// Use the Malay default when storage is unavailable.
	}

	setLocale(isLocale(saved) ? saved : 'ms');
}
